"""Writes results/p20_report.md from the p20 tables (p20_dnds_ci.tsv, p20_windows.tsv, p20_pairs_C.tsv).
Run after p20_dnds_ci.py:  py -3.12 p20_report.py
"""
import csv
import statistics as st
import sys
from collections import Counter, defaultdict

from p2_fetch_annotations import RESULTS

sys.stdout.reconfigure(encoding="utf8")
I, II, III, IIIM = ("ODC (i) interface, not catalytic", "ODC (ii) catalytic (13)", "ODC (iii) everything else",
                    "ODC (iii) everything else, mapped only")


def read(name):
    with open(RESULTS / name, encoding="utf8") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def fl(x):
    return float(x) if x not in ("", None) else None


def w(r):
    lo, hi = fl(r["ci_low"]), fl(r["ci_high"])
    return f"{r['dNdS'] or '-'} [{max(lo, 0) + 0.0:.3f}, {hi:.3f}]" if lo is not None else (r["dNdS"] or "-")


def main():
    ci = read("p20_dnds_ci.tsv")
    wins = read("p20_windows.tsv")
    pc = read("p20_pairs_C.tsv")
    pair = defaultdict(dict)
    for r in ci:
        pair[(r["set"], r["seq1"], r["seq2"])][r["region"]] = r
    gal = {k: v for k, v in pair.items() if k[0].startswith("Galdieria")}
    cpairs = {k: v for k, v in pair.items() if k[0].startswith("C:")}
    g_odc = [v["ODC"] for v in gal.values()]
    all_below = all(fl(r["ci_high"]) < 1 for r in g_odc)
    c_odc = [v["ODC"] for v in cpairs.values() if v["ODC"]["dNdS"] and v["ODC"]["saturated"] == "False"
             and v["ODC"]["too_little_divergence"] == "False"]
    cvals = sorted(fl(r["dNdS"]) for r in c_odc)
    gmed = st.median(fl(r["dNdS"]) for r in g_odc)
    n_below = sum(x < gmed for x in cvals)
    ci_lower = sum(1 for v in cpairs.values() if fl(v[I]["dNdS"]) is not None and fl(v[III]["dNdS"]) is not None
                   and fl(v[I]["dNdS"]) < fl(v[III]["dNdS"]))
    ci_sig = sum(1 for v in cpairs.values() if fl(v[I].get("p_vs_iii")) is not None and fl(v[I]["p_vs_iii"]) < 0.05
                 and fl(v[I]["dNdS"]) < fl(v[III]["dNdS"]))

    L = ["# p20: firm up or break the Galdieria ODC-half result", "",
         "Generated by `scripts/p20_report.py` from the tables written by `scripts/p20_dnds_ci.py` (method in its docstring).", "",
         "## Does the Galdieria ODC-half result survive?", "",
         f"**As a number, yes. As evidence that a dead ODC half is being kept as a structural element, no.**", "",
         f"- The ratio is real: ODC-half dN/dS {', '.join(w(r) for r in g_odc)} (95 % bootstrap CI, {len(g_odc)} pairs, "
         f"{'all' if all_below else 'not all'} CIs entirely below 1; no bootstrap replicate reached 1). It is below "
         "the linker in every pair (paired bootstrap p "
         + ", ".join(v["ODC"]["p_vs_linker"] for v in gal.values()) + ").",
         f"- But intact ODC halves are at least as constrained. Across {len(cvals)} unsaturated comparison pairs whose "
         f"two ODC halves are both intact (part C), the ODC-half dN/dS has median {st.median(cvals):.3f} (range "
         f"{cvals[0]:.3f}-{cvals[-1]:.3f}); {n_below} of {len(cvals)} are below Galdieria's {gmed:.2f}. A degraded "
         "Galdieria ODC half under the same constraint as a working one is what the hypothesis would predict, but it "
         "is also what an intact-like protein would show; the number does not separate the two.",
         f"- The interface pattern is not specific either. In Galdieria the interface codons are lower than the rest "
         f"(part B), but the same holds in {ci_lower} of {len(cpairs)} intact comparison pairs ({ci_sig} with p < 0.05). "
         "Interface conservation is a general property of these ODC halves, not a signature of a dead one.",
         "- The catalytic positions are not free in Galdieria (dN/dS about 0.04 over 12 codons, CI up to about 0.5). "
         "The two species carry the same substituted residues at 5 of their 6 shared lost sites (K69R, E274N, G276D, "
         "R277S, C360G; p10_degraded_pairs.tsv), so the losses predate the G. partita - G. sulphuraria split, and the "
         "substituted residues themselves have been conserved since.",
         "- The four Galdieria pairs are effectively one comparison (the two G. partita copies are 99.6 % identical, the "
         "two G. sulphuraria proteins 99.9 %).", "",
         "## Premises that did not match the data", "",
         "- PAML/codeml is not installed, so there is no likelihood-ratio test; the bootstrap is the only test.",
         "- The 311 rows of p10_all_fusions.tsv are not 311 AdoMetDC-then-ODC fusions: 224 are AdoMetDC before the "
         "PLP domain, 64 have the PLP domain first, 23 are our set.",
         "- The 66 bacterial rows are a different fusion: 64 have the PLP decarboxylase FIRST and a prokaryotic "
         "AdoMetDC (PF02675, not PF01536) after it, and their PLP domain is nearest the Selenomonas LDC/ODC, not human "
         "ODC. None has a structurally intact ODC half in p10 (11 incomplete, 4 undetermined, 1 degraded, 50 no model). "
         "They were still searched: "
         + summarize_bacteria(pc),
         "- Plasmodium, the known working bifunctional enzyme, fails the \"13/13 identical\" rule: 60 of its 65 fusions "
         "carry Phe at human Y331 (p10 sequence read). Its 310 congeneric pairs in the dS window were therefore not "
         "used as intact comparators. Y331F in a working enzyme means that rule is stricter than function.",
         "- p12_interface_residues.tsv on disk is from the p12 smoke run (70 interface residues, Lys69 missing, see "
         "the p12 fix). The interface-only set used here (interface minus the 13 catalytic positions) is the same "
         "66 residues either way.", "",
         "## A. Bootstrap CIs (Galdieria, p18's interpretable pairs)", "",
         f"Codons resampled with replacement, 1,000 replicates, seed 1; NG86. P(ratio >= 1) = share of replicates.", "",
         "| pair | region | codons | dN | dS | dN/dS [95 % CI] | P(ratio >= 1) | ODC vs linker p |", "|---|---|---|---|---|---|---|---|"]
    for (s, a, b), v in gal.items():
        for reg in ("AdoMetDC", "linker", "ODC"):
            r = v[reg]
            L.append(f"| {a} - {b} | {reg} | {r['codons']} | {r['dN']} | {r['dS']} | {w(r)} | {r['p_ratio_ge_1']} | "
                     f"{r.get('p_vs_linker') or ''} |")
    L += ["", "## B. Where is the constraint? (Galdieria)", "",
          "Position sets from the first sequence's ODC half mapped onto human ODC by structure (TM-align, CA <= 4 A). "
          "(iii) includes residues that do not map; the mapped-only version is shown too. (i) vs (iii): paired "
          "bootstrap p.", "",
          "| pair | map | (i) interface | (ii) catalytic | (iii) rest | (iii) rest, mapped | (i) vs (iii) p |", "|---|---|---|---|---|---|---|"]
    for (s, a, b), v in gal.items():
        L.append(f"| {a} - {b} | {v[I]['map_method'].split(' (')[1].split(',')[0]} | {w(v[I])} (n {v[I]['codons']}) | "
                 f"{w(v[II])} (n {v[II]['codons']}) | {w(v[III])} (n {v[III]['codons']}) | {w(v[IIIM])} | {v[I]['p_vs_iii']} |")
    L += ["", "The (i) vs (iii) result depends on which G. partita model supplies the map: Marc's A0A9C7PQ51 model "
          "gives p about 0.15, the AlphaFold DB A0A9C7PSW2 model about 0.02, with near-identical codons (the two "
          "copies are 99.6 % identical). The direction (interface lower) is the same in all four.", "",
          "Sliding windows (30 codons, step 10) over the Galdieria ODC halves, first pair shown; all pairs in "
          "p20_windows.tsv:", "",
          "| window | residues | human ODC span | codons | dN/dS | status | interface codons | catalytic codons |",
          "|---|---|---|---|---|---|---|---|"]
    first = next(iter(gal))
    for r in wins:
        if (r["set"], r["seq1"], r["seq2"]) == first:
            L.append(f"| {r['window']} | {r['seq1_residues']} | {r['human_odc_span']} | {r['codons']} | {r['dNdS'] or '-'} | "
                     f"{r['status']} | {r['interface_codons']} | {r['catalytic_codons']} |")
    L += ["", "## C. Comparison pairs with an intact ODC half", "",
          f"Candidate pairs: every pair within the same family and domain order among the 311 rows: {len(pc)} pairs. "
          f"With verified CDS for both: {sum(r['dS_whole'] != 'no verified CDS' for r in pc)}. In the dS window "
          f"0.05-1.0 (whole protein): {sum(r['in_window'] == 'True' for r in pc)}. Both ODC halves intact (p10 structure, "
          f"or 13/13 identical by sequence where there is no model): {sum(r['both_intact'] == 'True' for r in pc)}. "
          f"Both: {sum(r['in_window'] == 'True' and r['both_intact'] == 'True' for r in pc)} pairs, analysed with A and B. "
          "Every candidate pair with protein identity and dS is in p20_pairs_C.tsv.", "",
          "These pairs are not independent (many share a sequence, and a few families dominate); medians per family "
          "are descriptive, and no test across pairs was run.", "",
          "| family | pairs | AdoMetDC median | linker median | ODC median | ODC (i) interface | ODC (ii) catalytic | ODC (iii) rest |",
          "|---|---|---|---|---|---|---|---|"]
    fam = defaultdict(list)
    for k, v in cpairs.items():
        fam[k[0][3:]].append(v)
    for f_, vs in sorted(fam.items(), key=lambda x: -len(x[1])):
        def med(reg):
            x = [fl(v[reg]["dNdS"]) for v in vs if v[reg]["dNdS"] and v[reg]["saturated"] == "False"]
            return f"{abs(st.median(x)):.3f} ({len(x)})" if x else "-"
        L.append(f"| {f_} | {len(vs)} | {med('AdoMetDC')} | {med('linker')} | {med('ODC')} | {med(I)} | {med(II)} | {med(III)} |")
    L += ["", "Medians over pairs whose region dS is not saturated (count in brackets). Galdieria for comparison: "
          f"ODC {gmed:.3f}, interface {st.median(fl(v[I]['dNdS']) for v in gal.values()):.3f}, "
          f"rest {st.median(fl(v[III]['dNdS']) for v in gal.values()):.3f}.", "",
          "Two dinoflagellate pairs (Peridiniaceae, Thoracosphaeraceae) have AdoMetDC halves that differ but ODC "
          "halves and linkers identical at the DNA level, so no ODC ratio exists for them.", "",
          "Position maps for part C: by structure where a model exists, otherwise by local sequence alignment to P11926 ("
          + ", ".join(f"{k} {n}" for k, n in Counter(v[I]["map_method"].split(" (")[0] for v in cpairs.values()).items())
          + " pairs).", ""]
    (RESULTS / "p20_report.md").write_text("\n".join(L), encoding="utf8")


def summarize_bacteria(pc):
    b = [r for r in pc if r["group"] == "Bacteria"]
    no = sum(r["dS_whole"] == "no verified CDS" for r in b)
    win = sum(r["in_window"] == "True" for r in b)
    import json
    from p2_fetch_annotations import DATA
    notes = json.loads((DATA / "p20_cds" / "_p20_cds_notes.json").read_text(encoding="utf8"))["cds_notes"]
    accs = {r[k] for r in b for k in ("seq1", "seq2")}
    c = Counter("verified" if "identical" in notes[x] else "no ENA protein_id in UniParc" if "no ENA protein_id" in notes[x]
                else "ENA translation differs from UniParc" if "differs" in notes[x] else "other" for x in accs if x in notes)
    return (f"{len(b)} bacterial candidate pairs, {no} without a verified CDS for both members (of the {len(accs)} "
            f"bacterial sequences paired: " + ", ".join(f"{v} {k}" for k, v in c.most_common()) + f"), {win} in the dS "
            "window, none with both ODC halves intact.")


if __name__ == "__main__":
    main()
